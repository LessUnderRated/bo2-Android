#!/usr/bin/env bash
# scripts/check-runtime-android.sh — compile bo2-mac's portable runtime for Android and say what is still missing.
#
# Compiles every runtime file that is not a macOS backend (the patched tree from scripts/upstream.sh) to an arm64
# object with the NDK, for Zombies (BO2_TARGET_ZMS), then lists the symbols those objects need and nobody provides:
# what the Android backends (graphics, shaders, audio, controller) still owe, grouped. The lifted game code
# (sub_*, __remill_*) and the libraries (libc, libc++, Unicorn, libvpx, zlib) are left out of the list.
#
# No game file is read: snd_reverb_gen.inc, which the lift generates from the player's exe, is an empty placeholder.
# REQUIRE_STEAM=ON compiles the real Steam client path instead of the fixed answers (docs/STEAM.md); the other
# variant is compiled too, so both stay buildable. Runs on Linux, WSL or Git Bash. Exit 1 if a file does not compile.
set -euo pipefail
cd "$(dirname "$0")/.."
UP=android/build/upstream
[ -d "$UP/bo2-mac" ] || scripts/upstream.sh
SDK="${ANDROID_HOME:-${ANDROID_SDK_ROOT:-$HOME/Android/Sdk}}"
NDK="${ANDROID_NDK_HOME:-$SDK/ndk/$(sed -n 's/^ndk;//p' android/packages.txt)}"
case "$(uname -s)" in MINGW*|MSYS*|CYGWIN*) HOST=windows-x86_64; EXE=.exe ;; Darwin) HOST=darwin-x86_64; EXE= ;; *) HOST=linux-x86_64; EXE= ;; esac
BIN="$NDK/toolchains/llvm/prebuilt/$HOST/bin"
[ -x "$BIN/clang++$EXE" ] || { echo "no NDK clang at $BIN (set ANDROID_HOME or ANDROID_NDK_HOME)" >&2; exit 1; }
OUT=android/build/runtime-check
rm -rf "$OUT" && mkdir -p "$OUT/gen"
: > "$OUT/gen/snd_reverb_gen.inc"   # generated by the lift from the player's exe; empty until then

# Steam: by default the fixed answers (docs/STEAM.md); REQUIRE_STEAM=ON builds the real client path instead.
if [ "${REQUIRE_STEAM:-OFF}" = ON ]; then STEAM_DEF=-DBO2_REQUIRE_STEAM; STEAM_OTHER=; echo "  Steam: real client path (REQUIRE_STEAM=ON)"
else STEAM_DEF=; STEAM_OTHER=-DBO2_REQUIRE_STEAM; echo "  Steam: fixed answers (REQUIRE_STEAM=OFF)"; fi

R="$UP/bo2-mac/runtime"
FILES="win32/win32_runtime.cpp win32/kernel32_impl.cpp win32/user32_impl.cpp win32/remaining_dlls_impl.cpp
       win32/bo2_replay.cpp win32/heap_code.cpp win32/x86_guest_vm.cpp win32/interp.cpp win32/exception_adapter.cpp
       win32/dw_local.cpp win32/cull_native.cpp win32/skin_native.cpp win32/match_rules.cpp video/vpx_native.cpp
       audio/coreaudio_out.cpp win32/bo2_platform_android.cpp"
# This port's own Android backends (runtime/ in this repository), which need SDL's headers (Gradle clones SDL).
SDL_INC=$(ls -d android/build/sdl3/*/include 2>/dev/null | head -1 || true)
OURS="runtime/gfx/dxbc_to_vk.cpp runtime/gfx/vk/vk_core.cpp runtime/gfx/vk/vk_capture.cpp runtime/gfx/vk/vk_resources.cpp
      runtime/gfx/vk/vk_render.cpp runtime/gfx/vk/vk_frame.cpp runtime/gfx/vk/vk_window.cpp runtime/gfx/vk/vk_glsl.cpp
      runtime/gfx/vk/bc_decode.cpp"
# glslang (the NDK's copy, for GLSL -> SPIR-V on the phone): its Android.mk's sources minus the HLSL front end.
G="$NDK/sources/third_party/shaderc/third_party/glslang"
mkdir -p "$OUT/gen/glslang" "$OUT/glslang"
sed -n '/^#define GLSLANG_VERSION_GREATER_THAN/,$p' "$G/build_info.h.tmpl" > "$OUT/gen/glslang/tail.h"
{ printf '#ifndef GLSLANG_BUILD_INFO\n#define GLSLANG_BUILD_INFO\n#define GLSLANG_VERSION_MAJOR 11\n#define GLSLANG_VERSION_MINOR 11\n'
  printf '#define GLSLANG_VERSION_PATCH 0\n#define GLSLANG_VERSION_FLAVOR ""\n'; cat "$OUT/gen/glslang/tail.h"; } > "$OUT/gen/glslang/build_info.h"
GSRC="glslang/GenericCodeGen/CodeGen.cpp glslang/GenericCodeGen/Link.cpp OGLCompilersDLL/InitializeDll.cpp
      glslang/OSDependent/Unix/ossource.cpp SPIRV/GlslangToSpv.cpp SPIRV/InReadableOrder.cpp SPIRV/Logger.cpp
      SPIRV/SpvBuilder.cpp SPIRV/SpvPostProcess.cpp SPIRV/doc.cpp SPIRV/disassemble.cpp SPIRV/SpvTools.cpp"
for f in attribute Constant glslang_tab InfoSink Initialize Intermediate intermOut IntermTraverse iomapper limits \
         linkValidate parseConst ParseContextBase ParseHelper PoolAlloc propagateNoContraction reflection RemoveTree \
         Scan ShaderLang SpirvIntrinsics SymbolTable Versions; do GSRC="$GSRC glslang/MachineIndependent/$f.cpp"; done
for f in PpAtom PpContext Pp PpScanner PpTokens; do GSRC="$GSRC glslang/MachineIndependent/preprocessor/$f.cpp"; done
if [ -n "$SDL_INC" ]; then OURS="$OURS runtime/input/pad_sdl.cpp"; else echo "  (no SDL checkout yet: build the APK once; pad_sdl.cpp skipped)"; fi
fail=0
pids=()
# HLSLcc itself (the shader translator both backends use), quietly: it is upstream's, its warnings are not ours.
H="$UP/bo2-mac/third_party/HLSLcc"
mkdir -p "$OUT/hlslcc"
for f in "$H"/src/*.cpp "$H"/src/cbstring/*.c; do
    n=$(basename "${f%.*}")
    case "$f" in *.c) lang=(-x c -std=c11) ;; *) lang=(-std=c++14) ;; esac
    "$BIN/clang++$EXE" --target=aarch64-linux-android33 -c -O1 -fPIC -w "${lang[@]}" -I "$H" -I "$H/include" \
        -I "$H/src" -I "$H/src/internal_includes" -I "$H/src/cbstring" "$f" -o "$OUT/hlslcc/$n.o" > "$OUT/hlslcc/$n.log" 2>&1 &
    pids+=("$!:hlslcc/$n")
done
for f in $GSRC; do
    n=$(echo "$f" | tr '/' '_' | sed 's/\.cpp$//')
    "$BIN/clang++$EXE" --target=aarch64-linux-android33 -c -O1 -fPIC -w -std=c++17 -DGLSLANG_OSINCLUDE_UNIX \
        -I "$G" -I "$G/glslang/MachineIndependent" -I "$OUT/gen" "$G/$f" -o "$OUT/glslang/$n.o" > "$OUT/glslang/$n.log" 2>&1 &
    pids+=("$!:glslang/$n")
done
for f in $(for x in $FILES; do echo "$R/$x"; done) $OURS; do
    n=$(basename "$f" .cpp)
    "$BIN/clang++$EXE" --target=aarch64-linux-android33 -c -O1 -std=c++17 -fPIC -Wall -Wno-unused \
        -Wno-unused-parameter -Wno-packed-non-pod -Wno-missing-field-initializers -I runtime/gfx/vk -I "$G" \
        -DADDRESS_SIZE_BITS=32 -DBO2_NO_EXTRA_LIFTED -DBO2_TARGET_ZMS \
        -I "$UP/remill/include" -I "$R/win32" -I "$UP/bo2-mac/third_party/HLSLcc/include" \
        -I "$UP/unicorn/include" -I "$UP/libvpx" -I "$OUT/gen" ${SDL_INC:+-I "$SDL_INC"} \
        $STEAM_DEF "$f" -o "$OUT/$n.o" > "$OUT/$n.log" 2>&1 &
    pids+=("$!:$n")
done
# The other Steam path too, so neither stops building unnoticed (its object is not part of the symbol report).
mkdir -p "$OUT/other"
"$BIN/clang++$EXE" --target=aarch64-linux-android33 -c -O1 -std=c++17 -fPIC -w \
    -DADDRESS_SIZE_BITS=32 -DBO2_NO_EXTRA_LIFTED -DBO2_TARGET_ZMS $STEAM_OTHER \
    -I "$UP/remill/include" -I "$R/win32" -I "$UP/unicorn/include" -I "$OUT/gen" \
    "$R/win32/remaining_dlls_impl.cpp" -o "$OUT/other/remaining_dlls_impl.o" > "$OUT/other/remaining_dlls_impl.log" 2>&1 &
pids+=("$!:other/remaining_dlls_impl")
for pn in "${pids[@]}"; do
    if wait "${pn%%:*}"; then printf '  ok    %s (%s warnings)\n' "${pn#*:}" "$(grep -c 'warning:' "$OUT/${pn#*:}.log" || true)"
    else printf '  FAIL  %s\n' "${pn#*:}"; grep -m5 'error:' "$OUT/${pn#*:}.log" || true; fail=1; fi
done
[ "$fail" = 0 ] || exit 1

NM="$BIN/llvm-nm$EXE"
"$NM" -u "$OUT"/*.o "$OUT"/hlslcc/*.o "$OUT"/glslang/*.o | awk 'NF==2 && $1=="U"{print $2}' | sort -u > "$OUT/undef.txt"
"$NM" --defined-only "$OUT"/*.o "$OUT"/hlslcc/*.o "$OUT"/glslang/*.o | awk 'NF==3{print $3}' | sort -u > "$OUT/def.txt"
SYS="$NDK/toolchains/llvm/prebuilt/$HOST/sysroot/usr/lib/aarch64-linux-android/33"
for l in libc.so libm.so libdl.so liblog.so libaaudio.so libz.so; do "$NM" -D --defined-only "$SYS/$l"; done |
    awk '{print $NF}' | sed 's/@.*//' | sort -u > "$OUT/system.txt"
comm -23 "$OUT/undef.txt" "$OUT/def.txt" | comm -23 - "$OUT/system.txt" |
    grep -v -E '^(_ZN?K?St|_ZSt|_Zn[wa]m|_Zd[la]Pv|__cxa_|__gxx_|_Unwind|_ZTH|_ZTV|_ZTI|_ZTT|__dso_handle|__ehdr_start|atexit|__aarch64_)' |
    grep -v -E '^(SDL_|uc_|vpx_|inflate|deflate|compress|_?sub_[0-9a-f]+(_impl[0-9]*)?$|__remill_|__stub_call_fatal$)' > "$OUT/backend.txt" || true

# One line per backend: how many symbols it still owes, and which. An empty group is done.
group() {
    local names
    names=$(grep -E "$2" "$OUT/backend.txt" | tr '\n' ' ' || true)
    printf '  %-10s %3d  %s\n' "$1" "$(printf '%s' "$names" | wc -w)" "$names"
}
echo "Still owed by the Android backends ($(wc -l < "$OUT/backend.txt") symbols):"
group graphics '^gfx_'
group shaders '^bo2_(dxbc|msl)_'
group audio '^bo2_audio_'
group controller '^bo2_pad_'
others=$(grep -v -E '^(gfx_|bo2_(dxbc|msl|audio|pad)_)' "$OUT/backend.txt" | tr '\n' ' ' || true)
[ -z "$others" ] || echo "  unexpected: $others"
