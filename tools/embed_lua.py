#!/usr/bin/env python3
"""Embed a Lua source file into the shim as a C string constant.

The native Press Start path runs `scripts/lua/open_main_menu.lua` with no host
file and no environment variable, so the text has to live inside the binary.
Keeping the .lua as the single source of truth and generating the .inc at build
time means the file you edit with BO2_LUA_SRC/BO2_LUA_WATCH (the live console)
is byte-for-byte the file that ships.

    tools/embed_lua.py scripts/lua/open_main_menu.lua \
        runtime/win32/open_main_menu_lua.inc kOpenMainMenuLua

The output is committed so a fresh checkout compiles: rerun this after
editing the .lua.
"""
import sys
import ast
import os


def c_escape(chunk: bytes) -> str:
    out = []
    for b in chunk:
        c = chr(b)
        if c == '"':
            out.append('\\"')
        elif c == "\\":
            out.append("\\\\")
        elif c == "\n":
            out.append("\\n")
        elif c == "\t":
            out.append("\\t")
        elif 0x20 <= b < 0x7F:
            out.append(c)
        else:
            # Octal, not hex: "\x41" followed by a hex digit would swallow it.
            out.append(f"\\{b:03o}")
    return "".join(out)


def main(argv):
    if len(argv) != 4:
        sys.exit(__doc__)
    src, dst, sym = argv[1], argv[2], argv[3]
    data = open(src, "rb").read()

    lines = ["// GENERATED by tools/embed_lua.py — do not edit.",
             f"// Source of truth: {os.path.relpath(src)}",
             f"static const char {sym}[] ="]
    # One C string literal per source line keeps the generated file diffable:
    # a one-line change to the Lua shows up as a one-line change here.
    # keepends, NOT split("\n"): splitting drops the information about whether
    # the file ended with a newline and re-adding one to every piece appends a
    # spurious blank line, so the embedded text would be one byte longer than
    # the file it claims to be identical to.
    for raw in data.splitlines(keepends=True):
        lines.append(f'    "{c_escape(raw)}"')
    if not lines[3:]:
        lines.append('    ""')
    lines.append(";")

    # Self-check: the literals must decode back to the EXACT input bytes. A
    # payload that is "almost" its source is the worst kind of drift — it still
    # runs, so nothing ever tells you the shipped text and the text you are
    # editing have diverged.
    blob = "".join(ast.literal_eval(l.strip()) for l in lines[3:-1]).encode("latin1")
    if blob != data:
        sys.exit(f"embed_lua: round-trip mismatch ({len(blob)} bytes vs {len(data)})")

    text = "\n".join(lines) + "\n"

    old = open(dst, encoding="utf-8").read() if os.path.exists(dst) else None
    if old != text:
        open(dst, "w", encoding="utf-8").write(text)
        print(f"embed_lua: {src} -> {dst} ({len(data)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
