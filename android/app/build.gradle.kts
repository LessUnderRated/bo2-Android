// The APK: SDL's Java activity, libmain.so (android/native/CMakeLists.txt) and libSDL3.so. Laid out as
// LessUnderRated's Chronicle-rs android/app is. scripts/build.sh drives it.
//
// Batteries not included: no game file and no code derived from the game is part of this repository or its APK. The
// game core (the runtime and the game recompiled from the player's own Steam copy, libbo2core.so) is built on the
// player's own PC by scripts/package-game.sh, copied to the phone's game folder, and loaded by the app at run time.

plugins {
    id("com.android.application")
}

// One SDL checkout serves both halves: its Java glue is compiled here and CMake builds the library
// from it (FETCHCONTENT_SOURCE_DIR_SDL3), so the two cannot disagree.
val sdlTag = File(rootDir, "sdl3-tag.txt").readText().trim()
val sdlDir = File(rootDir, "build/sdl3/$sdlTag")
if (!File(sdlDir, "CMakeLists.txt").exists()) {
    sdlDir.parentFile.mkdirs()
    val clone = ProcessBuilder("git", "clone", "--depth", "1", "--branch", sdlTag,
        "https://github.com/libsdl-org/SDL.git", sdlDir.path).inheritIO().start()
    check(clone.waitFor() == 0) { "cloning SDL $sdlTag failed" }
}

// assets/licenses/: LICENSE, THIRD_PARTY_NOTICES.txt and licenses/*, copied at configuration time.
val licenseAssets = File(layout.buildDirectory.get().asFile, "generated/licenses")
File(licenseAssets, "licenses").let { out ->
    out.deleteRecursively()
    out.mkdirs()
    val repoRoot = rootDir.parentFile
    File(repoRoot, "LICENSE").copyTo(File(out, "LICENSE-GPL-3.0.txt"))
    File(repoRoot, "THIRD_PARTY_NOTICES.txt").copyTo(File(out, "THIRD_PARTY_NOTICES.txt"))
    File(repoRoot, "licenses").listFiles()?.forEach { it.copyTo(File(out, it.name)) }
}

// res/xml/network_security_config.xml, generated: cleartext HTTP is refused everywhere except to bo2-logd on the
// developer's PC (the bo2.logServer property, host:port, e.g. a Tailscale address), which the updater (Updater.java)
// talks to. The log itself goes over native sockets, which this config does not cover.
val generatedRes = File(layout.buildDirectory.get().asFile, "generated/bo2res")
File(generatedRes, "xml").let { out ->
    out.mkdirs()
    val server = (project.findProperty("bo2.logServer") as String?)?.trim().orEmpty()
    val host = server.substringBeforeLast(':', "").removePrefix("[").removeSuffix("]")
    val domain = if (host.isEmpty()) "" else """
    <domain-config cleartextTrafficPermitted="true">
        <domain includeSubdomains="false">$host</domain>
    </domain-config>"""
    File(out, "network_security_config.xml").writeText("""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by app/build.gradle.kts from bo2.logServer. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false" />$domain
</network-security-config>
""")
}

android {
    namespace = "io.github.lessunderrated.bo2"
    compileSdk = 36
    buildToolsVersion = "36.0.0"
    ndkVersion = "28.2.13676358"

    defaultConfig {
        applicationId = "io.github.lessunderrated.bo2"
        // DXVK needs Vulkan 1.3, whose entry points are in the NDK's libvulkan.so from API 33.
        minSdk = 33
        targetSdk = 36
        // The version code is the build time in minutes since 2020 (scripts/build.sh passes the time): it only grows,
        // so each build installs over the last as an upgrade whatever happens to the history (a commit count fell
        // from 85 to 34 when the history was cut for the public repository, and Android refuses a lower version over
        // a higher one). The version name keeps the branch's commit count, which the launcher shows.
        val buildNumber = (findProperty("bo2.buildNumber") as String?)?.toIntOrNull() ?: 1
        val buildTime = (findProperty("bo2.buildTime") as String?)?.toLongOrNull() ?: (System.currentTimeMillis() / 1000)
        versionCode = ((buildTime - 1_577_836_800L) / 60).toInt()
        versionName = "0.1.$buildNumber"

        ndk {
            abiFilters += listOf("arm64-v8a")
        }
        externalNativeBuild {
            cmake {
                arguments += listOf(
                    "-DANDROID_STL=c++_shared",
                    "-DFETCHCONTENT_SOURCE_DIR_SDL3=${sdlDir.path}",
                    "-DCMAKE_CXX_SCAN_FOR_MODULES=OFF",
                )
                targets += listOf("main", "SDL3-shared")
            }
        }

        val documentsAuthority = "$applicationId.documents"
        manifestPlaceholders["documentsAuthority"] = documentsAuthority
        buildConfigField("String", "DOCUMENTS_AUTHORITY", "\"$documentsAuthority\"")
        // Where the app sends its log (host:port of tools/bo2-logd, e.g. a PC's Tailscale address), and the commit it
        // was built from. Both come from scripts/build.sh; empty: the log stays on the phone.
        buildConfigField("String", "LOG_SERVER", "\"${(findProperty("bo2.logServer") as String?) ?: ""}\"")
        buildConfigField("String", "GIT_COMMIT", "\"${(findProperty("bo2.gitCommit") as String?) ?: ""}\"")
        // When it was built (Unix seconds, from scripts/build.sh; 0 when unknown), for the launcher's version line.
        buildConfigField("long", "BUILD_TIME", "${(findProperty("bo2.buildTime") as String?)?.toLongOrNull() ?: 0}L")
    }

    buildTypes {
        release {
            isMinifyEnabled = false
        }
        debug {
            isJniDebuggable = true
            // A recompiled game at -O0 cannot hold a frame rate; the native side is always optimised.
            externalNativeBuild { cmake { arguments += "-DCMAKE_BUILD_TYPE=RelWithDebInfo" } }
        }
    }

    buildFeatures {
        buildConfig = true
    }

    sourceSets {
        getByName("main") {
            java.srcDirs(File(sdlDir, "android-project/app/src/main/java"))
            // The license texts travel with every APK, the shell's included (THIRD_PARTY_NOTICES.md).
            assets.srcDirs(licenseAssets)
            res.srcDirs(generatedRes)
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    externalNativeBuild {
        cmake {
            path = File(rootDir, "native/CMakeLists.txt")
            version = "3.31.6"
        }
    }

    // Native libraries are stored compressed: libmain.so is 290 MB of recompiled game code and deflates to about 86 MB,
    // and every update is downloaded (in-app over Tailscale, or from a release). Android extracts it once at install;
    // stored uncompressed it would be mapped from the APK instead, but the download would be 3.4 times larger.
    packaging {
        jniLibs { useLegacyPackaging = true }
    }
    // libmain.so ships stripped (Gradle's default): about 14 MB of debug info and symbol tables the phone never reads.
    // Crash reports (log.cpp) name functions through dladdr, which reads only the dynamic symbol table, kept by the
    // strip; and they, like the in-app profiler, give offsets into libmain.so, which scripts/build.sh symbolises on the
    // PC against the unstripped copy it archives by build id (BO2_SYMBOLS, scripts/env.sh).
}
