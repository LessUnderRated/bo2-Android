/**
 * New builds from the developer's PC, over Tailscale, with no adb and no GitHub: bo2-logd (tools/bo2-logd) serves the
 * APK that scripts/build.sh --publish left there. At each launch of the setup screen, before the game starts, this
 * asks the server what it has (GET /v1/apk/latest: commit, size, sha256). When that sha256 is not the installed APK's
 * own, it offers the build; Update downloads it (resumable, GET /v1/apk/download with Range), checks its size and
 * sha256, and installs it through a PackageInstaller session (Android asks the player to confirm).
 *
 * Only in builds made for a log server (BuildConfig.LOG_SERVER, the Gradle property bo2.logServer); the network
 * security config (generated by build.gradle.kts) allows cleartext HTTP to that host only. A server out of reach
 * costs one log line and nothing else.
 */
final class Updater {
    private static final String PREFS = "updater";
    private static final AtomicBoolean CHECKED = new AtomicBoolean();
    private static final Handler MAIN = new Handler(Looper.getMainLooper());
    /** An offer accepted while installs from this app were not allowed yet: resumed when the player comes back. */
    private static Map<String, String> pending;

    private Updater() {
    }

    private static String base() {
        return "http://" + BuildConfig.LOG_SERVER;
    }

    /** Once per process, from SetupActivity: ask the PC whether it has a build this phone does not. */
    static void check(Activity activity) {
        if (BuildConfig.LOG_SERVER.isEmpty() || SetupActivity.gameRunning || !CHECKED.compareAndSet(false, true)) {
            return;
        }
        final Context app = activity.getApplicationContext();
        new Thread(() -> {
            Map<String, String> latest;
            try {
                latest = fetchLatest("/v1/apk/latest");
            } catch (IOException e) {
                SetupActivity.log("[UPDATE] " + BuildConfig.LOG_SERVER + " not reachable: " + e.getMessage());
                return;
            }
            if (latest == null) {
                SetupActivity.log("[UPDATE] no build published on " + BuildConfig.LOG_SERVER);
                checkCore(activity);   // the app stays as it is; the game core may still be newer
                return;
            }
            String mine = installedSha(app);
            if (latest.get("sha256").equalsIgnoreCase(mine)) {
                SetupActivity.log("[UPDATE] up to date (build " + latest.get("commit") + ")");
                checkCore(activity);   // only once the app is current: one offer at a time
                return;
            }
            SetupActivity.log("[UPDATE] build " + latest.get("commit") + " is on the PC; installed " + BuildConfig.GIT_COMMIT);
            MAIN.post(() -> offer(activity, latest));
        }, "bo2-update-check").start();
    }

    /** SetupActivity.onResume: back from the "install unknown apps" setting with an offer accepted. */
    static void onResume(Activity activity) {
        Map<String, String> latest = pending;
        if (latest != null && activity.getPackageManager().canRequestPackageInstalls()) {
            pending = null;
            download(activity, latest);
        }
    }

    // ---- What the PC has, and what is installed --------------------------------------------------------------------

    /** An info file (latest.txt, core.txt) as key=value pairs, or null when the server has none (404). */
    private static Map<String, String> fetchLatest(String path) throws IOException {
        HttpURLConnection c = (HttpURLConnection) new URL(base() + path).openConnection();
        c.setConnectTimeout(3000);
        c.setReadTimeout(3000);
        try {
            int code = c.getResponseCode();
            if (code == 404) {
                return null;
            }
            if (code != 200) {
                throw new IOException("HTTP " + code);
            }
            Map<String, String> out = new HashMap<>();
            try (BufferedReader r = new BufferedReader(new InputStreamReader(c.getInputStream(), StandardCharsets.UTF_8))) {
                for (String line; (line = r.readLine()) != null; ) {
                    int eq = line.indexOf('=');
                    if (eq > 0) {
                        out.put(line.substring(0, eq).trim(), line.substring(eq + 1).trim());
                    }
                }
            }
            if (!out.containsKey("sha256") || !out.containsKey("size")) {
                throw new IOException(path + " without sha256 or size");
            }
            out.putIfAbsent("commit", "?");
            return out;
        } finally {
            c.disconnect();
        }
    }

    /** The installed APK's sha256, computed once per install (keyed by its install time) and kept. */
    private static String installedSha(Context context) {
        SharedPreferences prefs = context.getSharedPreferences(PREFS, Context.MODE_PRIVATE);
        long installed;
        try {
            PackageInfo info = context.getPackageManager().getPackageInfo(context.getPackageName(), 0);
            installed = info.lastUpdateTime;
        } catch (PackageManager.NameNotFoundException e) {
            installed = 0;
        }
        if (prefs.getLong("apk_time", -1) == installed) {
            return prefs.getString("apk_sha", "");
        }
        String sha;
        try {
            sha = sha256(new File(context.getApplicationInfo().sourceDir), null);
        } catch (IOException e) {
            return "";
        }
        prefs.edit().putLong("apk_time", installed).putString("apk_sha", sha).apply();
        return sha;
    }

    interface Progress {
        void at(long done);
    }

    private static String sha256(File file, Progress progress) throws IOException {
        MessageDigest md;
        try {
            md = MessageDigest.getInstance("SHA-256");
        } catch (NoSuchAlgorithmException e) {
            throw new IOException(e);
        }
        byte[] buf = new byte[1 << 20];
        long done = 0;
        try (InputStream in = new FileInputStream(file)) {
            for (int n; (n = in.read(buf)) > 0; ) {
                md.update(buf, 0, n);
                done += n;
                if (progress != null) {
                    progress.at(done);
                }
            }
        }
        StringBuilder hex = new StringBuilder();
        for (byte b : md.digest()) {
            hex.append(String.format("%02x", b));
        }
        return hex.toString();
    }

    private static long size(Map<String, String> latest) {
        try {
            return Long.parseLong(latest.get("size"));
        } catch (NumberFormatException e) {
            return -1;
        }
    }

    // ---- The offer ---------------------------------------------------------------------------------------------------

    private static boolean gone(Activity a) {
        return a.isFinishing() || a.isDestroyed();
    }

    private static AlertDialog.Builder dialog(Activity a) {
        return new AlertDialog.Builder(a, android.R.style.Theme_DeviceDefault_Dialog_Alert);
    }

    private static void offer(Activity activity, Map<String, String> latest) {
        if (gone(activity) || SetupActivity.gameRunning) {
            return;
        }
        long mb = Math.max(1, size(latest) >> 20);
        dialog(activity)
            .setTitle(R.string.update_title)
            .setMessage(activity.getString(R.string.update_offer, latest.get("commit"), mb))
            .setNegativeButton(R.string.update_not_now, null)
            .setPositiveButton(R.string.update_install, (d, w) -> {
                if (activity.getPackageManager().canRequestPackageInstalls()) {
                    download(activity, latest);
                } else {
                    askInstallPermission(activity, latest);
                }
            })
            .show();
    }

    private static void askInstallPermission(Activity activity, Map<String, String> latest) {
        dialog(activity)
            .setTitle(R.string.update_title)
            .setMessage(R.string.update_permission)
            .setNegativeButton(R.string.update_not_now, null)
            .setPositiveButton(R.string.update_open_settings, (d, w) -> {
                pending = latest;
                activity.startActivity(new Intent(Settings.ACTION_MANAGE_UNKNOWN_APP_SOURCES,
                    Uri.parse("package:" + activity.getPackageName())));
            })
            .show();
    }

    // ---- Download, check, install -----------------------------------------------------------------------------------

    private static void download(Activity activity, Map<String, String> latest) {
        if (gone(activity)) {
            return;
        }
        final long size = size(latest);
        final String sha = latest.get("sha256").toLowerCase();
        LinearLayout box = new LinearLayout(activity);
        box.setOrientation(LinearLayout.VERTICAL);
        int pad = Math.round(20 * activity.getResources().getDisplayMetrics().density);
        box.setPadding(pad, pad / 2, pad, 0);
        TextView text = new TextView(activity);
        ProgressBar bar = new ProgressBar(activity, null, android.R.attr.progressBarStyleHorizontal);
        bar.setMax(1000);
        box.addView(text);
        box.addView(bar);
        final AtomicBoolean cancel = new AtomicBoolean();
        AlertDialog progress = dialog(activity)
            .setTitle(activity.getString(R.string.update_downloading, latest.get("commit")))
            .setView(box)
            .setCancelable(false)
            .setNegativeButton(R.string.cancel, (d, w) -> cancel.set(true))
            .show();
        final Context app = activity.getApplicationContext();
        new Thread(() -> {
            String failure = null;
            try {
                File dir = app.getExternalCacheDir();
                if (dir == null) {
                    throw new IOException("no cache directory");
                }
                File apk = new File(dir, "update.apk");
                fetch("/v1/apk/download", apk, new File(dir, "update.sha"), size, sha, cancel, (done) -> show(text, bar, R.string.update_progress, done, size));
                if (cancel.get()) {
                    MAIN.post(progress::dismiss);
                    return;
                }
                String got = sha256(apk, (done) -> show(text, bar, R.string.update_checking, done, size));
                if (!got.equals(sha)) {
                    apk.delete();
                    throw new IOException(app.getString(R.string.update_mismatch));
                }
                MAIN.post(() -> text.setText(R.string.update_installing));
                install(app, apk, size);
                SetupActivity.log("[UPDATE] build " + latest.get("commit") + " downloaded and handed to the installer");
            } catch (IOException e) {
                failure = e.getMessage();
                SetupActivity.log("[UPDATE] failed: " + failure);
            }
            final String why = failure;
            MAIN.post(() -> {
                progress.dismiss();
                if (why != null && !gone(activity)) {
                    dialog(activity).setTitle(R.string.update_title)
                        .setMessage(activity.getString(R.string.update_failed, why))
                        .setPositiveButton(android.R.string.ok, null).show();
                }
            });
        }, "bo2-update-download").start();
    }

    private static long lastShown;

    private static void show(TextView text, ProgressBar bar, int format, long done, long size) {
        long now = System.nanoTime();
        if (now - lastShown < 200_000_000L && done < size) {
            return;
        }
        lastShown = now;
        MAIN.post(() -> {
            text.setText(text.getContext().getString(format, done >> 20, size >> 20));
            bar.setProgress(size > 0 ? (int) (done * 1000 / size) : 0);
        });
    }

    /** A published file (`path` on the server) into `apk`, resuming a partial download of the same build (`shaFile`
     *  names which build it is). */
    private static void fetch(String path, File apk, File shaFile, long size, String sha, AtomicBoolean cancel,
                              Progress progress) throws IOException {
        String partialOf = "";
        if (shaFile.exists()) {
            try (InputStream in = new FileInputStream(shaFile)) {
                partialOf = new String(in.readAllBytes(), StandardCharsets.UTF_8).trim();
            }
        }
        if (!partialOf.equals(sha) || apk.length() > size) {
            apk.delete();
        }
        try (OutputStream out = new FileOutputStream(shaFile)) {
            out.write(sha.getBytes(StandardCharsets.UTF_8));
        }
        long have = apk.length();
        if (have == size) {
            return;
        }
        HttpURLConnection c = (HttpURLConnection) new URL(base() + path).openConnection();
        c.setConnectTimeout(5000);
        c.setReadTimeout(30000);
        if (have > 0) {
            c.setRequestProperty("Range", "bytes=" + have + "-");
        }
        try {
            int code = c.getResponseCode();
            boolean append = code == 206;
            if (code != 200 && !append) {
                throw new IOException("HTTP " + code + " from " + BuildConfig.LOG_SERVER);
            }
            if (!append) {
                have = 0;
            }
            byte[] buf = new byte[256 << 10];
            try (InputStream in = c.getInputStream(); OutputStream out = new FileOutputStream(apk, append)) {
                for (int n; (n = in.read(buf)) > 0; ) {
                    out.write(buf, 0, n);
                    have += n;
                    progress.at(have);
                    if (cancel.get()) {
                        return;   // the partial file stays: Update resumes it
                    }
                }
            }
        } finally {
            c.disconnect();
        }
        if (apk.length() != size) {
            throw new IOException("download stopped at " + (apk.length() >> 20) + " of " + (size >> 20) + " MB");
        }
    }

    /** Hands the APK to a PackageInstaller session; InstallResult forwards Android's confirmation screen. */
    private static void install(Context context, File apk, long size) throws IOException {
        PackageInstaller installer = context.getPackageManager().getPackageInstaller();
        PackageInstaller.SessionParams params = new PackageInstaller.SessionParams(
            PackageInstaller.SessionParams.MODE_FULL_INSTALL);
        params.setAppPackageName(context.getPackageName());
        params.setSize(size);
        // After the first install made by this app, later ones may go through without a prompt.
        params.setRequireUserAction(PackageInstaller.SessionParams.USER_ACTION_NOT_REQUIRED);
        int id = installer.createSession(params);
        try (PackageInstaller.Session session = installer.openSession(id)) {
            byte[] buf = new byte[1 << 20];
            try (InputStream in = new FileInputStream(apk); OutputStream out = session.openWrite("base.apk", 0, size)) {
                for (int n; (n = in.read(buf)) > 0; ) {
                    out.write(buf, 0, n);
                }
                session.fsync(out);
            }
            Intent done = new Intent(context, InstallResult.class);
            PendingIntent pi = PendingIntent.getBroadcast(context, id, done,
                PendingIntent.FLAG_UPDATE_CURRENT | PendingIntent.FLAG_MUTABLE);
            session.commit(pi.getIntentSender());
        } catch (IOException | RuntimeException e) {
            installer.abandonSession(id);
            throw e instanceof IOException ? (IOException) e : new IOException(e.getMessage());
        }
    }

    // ---- The game core (GameCore.java), from the same PC -------------------------------------------------------------
    // The APK carries no game; the player's core, built on their PC from their own copy (scripts/package-game.sh) and
    // published gzipped beside the APK (build.sh --publish: core.txt, latest-core.so.gz), comes down the same way:
    // offered when this phone has none or another one, downloaded resumably, unpacked, checked (sha256 of the
    // unpacked library) and put where the app loads it. Checked once the APK itself is current.

    private static final AtomicBoolean CORE_CHECKED = new AtomicBoolean();

    /** The installed core's sha256, computed once per file (keyed by its size and time) and kept. */
    private static String installedCoreSha(Context context) {
        File core = GameCore.installed(context);
        if (!core.isFile()) {
            return "";
        }
        SharedPreferences prefs = context.getSharedPreferences(PREFS, Context.MODE_PRIVATE);
        String key = core.length() + ":" + core.lastModified();
        if (key.equals(prefs.getString("core_key", ""))) {
            return prefs.getString("core_sha", "");
        }
        try {
            String sha = sha256(core, null);
            prefs.edit().putString("core_key", key).putString("core_sha", sha).apply();
            return sha;
        } catch (IOException e) {
            return "";
        }
    }

    private static void checkCore(Activity activity) {
        if (!CORE_CHECKED.compareAndSet(false, true)) {
            return;
        }
        Context app = activity.getApplicationContext();
        Map<String, String> latest;
        try {
            latest = fetchLatest("/v1/core/latest");
        } catch (IOException e) {
            SetupActivity.log("[CORE] " + BuildConfig.LOG_SERVER + ": " + e.getMessage());
            return;
        }
        if (latest == null) {
            SetupActivity.log("[CORE] no game core published on " + BuildConfig.LOG_SERVER);
            return;
        }
        boolean missing = !GameCore.installed(app).isFile();
        if (!missing && latest.get("sha256").equalsIgnoreCase(installedCoreSha(app))) {
            SetupActivity.log("[CORE] up to date (" + latest.get("commit") + ")");
            return;
        }
        SetupActivity.log("[CORE] core " + latest.get("commit") + " is on the PC" + (missing ? "; this phone has none" : ""));
        MAIN.post(() -> offerCore(activity, latest, missing));
    }

    private static long gzSize(Map<String, String> latest) {
        try {
            return Long.parseLong(latest.getOrDefault("gz_size", "-1"));
        } catch (NumberFormatException e) {
            return -1;
        }
    }

    private static void offerCore(Activity activity, Map<String, String> latest, boolean missing) {
        if (gone(activity) || SetupActivity.gameRunning) {
            return;
        }
        long mb = Math.max(1, gzSize(latest) >> 20);
        dialog(activity)
            .setTitle(R.string.core_title)
            .setMessage(activity.getString(missing ? R.string.core_offer_missing : R.string.core_offer_newer,
                latest.get("commit"), mb))
            .setNegativeButton(R.string.update_not_now, null)
            .setPositiveButton(R.string.core_download, (d, w) -> downloadCore(activity, latest))
            .show();
    }

    private static void downloadCore(Activity activity, Map<String, String> latest) {
        if (gone(activity)) {
            return;
        }
        final long gz = gzSize(latest);
        final long size = size(latest);
        final String sha = latest.get("sha256").toLowerCase();
        LinearLayout box = new LinearLayout(activity);
        box.setOrientation(LinearLayout.VERTICAL);
        int pad = Math.round(20 * activity.getResources().getDisplayMetrics().density);
        box.setPadding(pad, pad / 2, pad, 0);
        TextView text = new TextView(activity);
        ProgressBar bar = new ProgressBar(activity, null, android.R.attr.progressBarStyleHorizontal);
        bar.setMax(1000);
        box.addView(text);
        box.addView(bar);
        final AtomicBoolean cancel = new AtomicBoolean();
        AlertDialog progress = dialog(activity)
            .setTitle(activity.getString(R.string.core_downloading, latest.get("commit")))
            .setView(box)
            .setCancelable(false)
            .setNegativeButton(R.string.cancel, (d, w) -> cancel.set(true))
            .show();
        final Context app = activity.getApplicationContext();
        new Thread(() -> {
            String failure = null;
            try {
                File dir = new File(app.getFilesDir(), "core");
                dir.mkdirs();
                File packed = new File(dir, "download.so.gz");
                fetch("/v1/core/download", packed, new File(dir, "download.sha"), gz, sha, cancel,
                    (done) -> show(text, bar, R.string.update_progress, done, gz));
                if (cancel.get()) {
                    MAIN.post(progress::dismiss);
                    return;
                }
                File unpacked = new File(dir, "download.so");
                String got = gunzip(packed, unpacked, (done) -> show(text, bar, R.string.core_unpacking, done, size));
                if (!got.equals(sha)) {
                    unpacked.delete();
                    packed.delete();
                    throw new IOException(app.getString(R.string.update_mismatch));
                }
                GameCore.install(app, unpacked);
                packed.delete();
                SetupActivity.log("[CORE] core " + latest.get("commit") + " installed (" + size + " bytes)");
            } catch (IOException e) {
                failure = e.getMessage();
                SetupActivity.log("[CORE] download failed: " + failure);
            }
            final String why = failure;
            MAIN.post(() -> {
                progress.dismiss();
                if (gone(activity)) {
                    return;
                }
                if (why != null) {
                    dialog(activity).setTitle(R.string.core_title)
                        .setMessage(activity.getString(R.string.update_failed, why))
                        .setPositiveButton(android.R.string.ok, null).show();
                } else if (activity instanceof SetupActivity) {
                    ((SetupActivity) activity).coreChanged();
                }
            });
        }, "bo2-core-download").start();
    }

    /** `from` (gzip) unpacked into `to`; returns the sha256 of what was written. */
    private static String gunzip(File from, File to, Progress progress) throws IOException {
        MessageDigest md;
        try {
            md = MessageDigest.getInstance("SHA-256");
        } catch (NoSuchAlgorithmException e) {
            throw new IOException(e);
        }
        to.delete();
        byte[] buf = new byte[1 << 20];
        long done = 0;
        try (InputStream in = new java.util.zip.GZIPInputStream(new FileInputStream(from), 1 << 16);
             OutputStream out = new FileOutputStream(to)) {
            for (int n; (n = in.read(buf)) > 0; ) {
                out.write(buf, 0, n);
                md.update(buf, 0, n);
                done += n;
                progress.at(done);
            }
        }
        StringBuilder hex = new StringBuilder();
        for (byte b : md.digest()) {
            hex.append(String.format("%02x", b));
        }
        return hex.toString();
    }

    /** The installer's answer: its confirmation screen to show, or how it ended. */
    public static final class InstallResult extends BroadcastReceiver {
        @Override
        public void onReceive(Context context, Intent intent) {
            int status = intent.getIntExtra(PackageInstaller.EXTRA_STATUS, PackageInstaller.STATUS_FAILURE);
            if (status == PackageInstaller.STATUS_PENDING_USER_ACTION) {
                Intent confirm = intent.getParcelableExtra(Intent.EXTRA_INTENT, Intent.class);
                if (confirm != null) {
                    confirm.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK);
                    context.startActivity(confirm);
                }
                return;
            }
            if (status != PackageInstaller.STATUS_SUCCESS) {
                String message = intent.getStringExtra(PackageInstaller.EXTRA_STATUS_MESSAGE);
                SetupActivity.log("[UPDATE] install failed (" + status + "): " + message);
                Toast.makeText(context, context.getString(R.string.update_failed, String.valueOf(message)),
                    Toast.LENGTH_LONG).show();
            }
        }
    }
}
