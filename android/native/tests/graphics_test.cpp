// Host tests for the graphics settings (scripts/test-host.sh runs them).
#include "graphics.hpp"

#include <algorithm>
#include <cstdio>

using namespace bo2gfx;

static int failures = 0;
#define CHECK(cond)                                                                       \
    do {                                                                                  \
        if (!(cond)) {                                                                    \
            std::fprintf(stderr, "%s:%d: CHECK(%s) failed\n", __FILE__, __LINE__, #cond); \
            ++failures;                                                                   \
        }                                                                                 \
    } while (0)

static bool has(const std::vector<std::string>& v, const std::string& s) {
    return std::find(v.begin(), v.end(), s) != v.end();
}

// An invented config in the game's format, not a real player's file.
static const char* kConfig =
    "// generated by the game\n"
    "seta com_maxfps \"85\"\n"
    "seta sm_enable \"1\"\n"
    "seta sm_sunShadowSmall \"0\"\n"
    "seta r_ssao \"2\"\n"
    "seta r_dof_enable \"1\"\n"
    "seta r_fxaa \"0\"\n"
    "seta r_aaSamples \"4\"\n"
    "seta r_picmip_manual \"0\"\n"
    "seta r_picmip \"0\"\n"
    "seta r_texFilterAnisoMax \"16\"\n"
    "seta cg_fov_default \"80\"\n"
    "seta ai_corpseCount \"8\"\n"
    "seta sm_maxLights \"4\"\n"
    "seta r_lodScaleRigid \"1\"\n";

static void parses_seta_lines() {
    auto m = parse_config(kConfig);
    CHECK(m["com_maxfps"] == "85");
    CHECK(m["r_aasamples"] == "4");  // names are case-insensitive in the engine; stored lower-case
    CHECK(m.count("generated") == 0);
}

static void low_preset_forces_the_cheap_values() {
    auto c = commands(preset(Preset::Low), parse_config(kConfig));
    CHECK(has(c.send, "set com_maxfps 70"));  // the cap + 10: the frame queue paces, not the game
    CHECK(has(c.send, "set sm_enable 0"));   // Low: no shadow passes (they cost the main core)
    CHECK(has(c.send, "set r_ssao 0"));
    CHECK(has(c.send, "set r_dof_enable 0"));
    CHECK(has(c.send, "set r_aaSamples 1"));
    CHECK(has(c.send, "set r_picmip_manual 1"));
    CHECK(has(c.send, "set r_picmip 1"));
    CHECK(has(c.send, "set ai_corpseCount 2"));
    CHECK(has(c.send, "set sm_maxLights 1"));
    CHECK(has(c.send, "set r_lodScaleRigid 2.5"));   // the big maps' lever: models LOD out sooner
    for (const auto& line : c.send) CHECK(line.size() <= 80);
}

static void dvars_missing_from_the_config_are_not_sent() {
    auto c = commands(preset(Preset::Low), parse_config(kConfig));
    // Not in kConfig: r_picmip_bump, r_picmip_spec, fx_marks_range.
    CHECK(has(c.skipped, "r_picmip_bump") && has(c.skipped, "fx_marks_range"));
    for (const auto& line : c.send) CHECK(line.find("fx_marks_range") == std::string::npos);
}

static void own_puts_the_players_values_back() {
    Settings s = preset(Preset::Own);
    s.frame_cap = -1;
    auto c = commands(s, parse_config(kConfig));
    CHECK(has(c.send, "set r_ssao 2"));
    CHECK(has(c.send, "set r_aaSamples 4"));
    CHECK(has(c.send, "set com_maxfps 85"));
    CHECK(has(c.send, "set cg_fov_default 80"));
    // The crowd trims go back to the game's defaults, not left as a preset forced them.
    CHECK(has(c.send, "set ai_corpseCount 8"));
    CHECK(has(c.send, "set sm_maxLights 4"));
    CHECK(has(c.send, "set r_lodScaleRigid 1"));
    CHECK(!has(c.skipped, "r_ssao") && !has(c.skipped, "cg_fov_default"));
}

static void fov_is_clamped_and_kept_across_presets() {
    Settings s;
    s.fov = 120;
    Settings p = preset(Preset::High, s);
    CHECK(p.fov == 120);
    auto c = commands(p, parse_config(kConfig));
    CHECK(has(c.send, "set cg_fov_default 90"));
    CHECK(has(c.send, "set ai_corpseCount 4"));
}

// The upscaler is the port's presentation, not a dvar: every preset picks SGSR, and no command is sent for it.
static void every_preset_upscales_with_sgsr() {
    Settings s;
    s.upscaler = 0;
    for (Preset p : {Preset::Low, Preset::Medium, Preset::High, Preset::Own}) {
        Settings q = preset(p, s);
        CHECK(q.upscaler == 1);
        auto c = commands(q, parse_config(kConfig));
        for (const auto& line : c.send) CHECK(line.find("upscal") == std::string::npos);
    }
}

// r_zfar replaces the map's own culling distance: only ever set nearer than it, else left at 0 (the map's own).
static void view_distance_never_goes_past_the_maps_own() {
    CHECK(cull_distance(-1, 0.f) == 0.f);        // the map's own: r_zfar off
    CHECK(cull_distance(5000, 0.f) == 5000.f);   // a map with no culling distance: the setting
    CHECK(cull_distance(5000, 9000.f) == 5000.f);
    CHECK(cull_distance(5000, 4000.f) == 0.f);   // the map's own is nearer: it stays
    CHECK(cull_distance(5000, 5000.f) == 0.f);
    CHECK(cull_distance(5000, -1.f) == 0.f);     // unreadable: leave the game alone
    CHECK(preset(Preset::Low).view_distance == 5000);
    CHECK(preset(Preset::Medium).view_distance == 8000);
    CHECK(preset(Preset::High).view_distance == -1 && preset(Preset::Own).view_distance == -1);
    // r_zfar is never a plain `set` line: it follows the map (bo2_view_distance_tick).
    auto c = commands(preset(Preset::Low), parse_config(kConfig));
    for (const auto& line : c.send) CHECK(line.find("r_zfar") == std::string::npos);
}

int main() {
    parses_seta_lines();
    view_distance_never_goes_past_the_maps_own();
    every_preset_upscales_with_sgsr();
    low_preset_forces_the_cheap_values();
    dvars_missing_from_the_config_are_not_sent();
    own_puts_the_players_values_back();
    fov_is_clamped_and_kept_across_presets();
    if (failures) {
        std::fprintf(stderr, "graphics_test: %d failure(s)\n", failures);
        return 1;
    }
    std::puts("graphics_test: all passed");
    return 0;
}
